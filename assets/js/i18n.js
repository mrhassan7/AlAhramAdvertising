/* ==========================================================================
   محرك اللغة
   ========================================================================== */
(function () {
  var STORAGE_KEY = 'ahram-lang';

  function saved() {
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }

  window.currentLang = function () {
    return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'ar';
  };

  window.t = function (key, vars) {
    var lang = window.currentLang();
    var dict = window.I18N[lang] || window.I18N.ar;
    var str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.split('{' + k + '}').join(vars[k]);
      });
    }
    return str;
  };

  /** يطبّق النصوص على كل عنصر يحمل data-i18n */
  window.applyI18n = function (root) {
    var scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var value = window.t(key);
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = value;
      else el.textContent = value;
    });

    /* data-i18n-attr="placeholder:form.namePh; aria-label:common.close" */
    scope.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var bits = pair.split(':');
        if (bits.length === 2) el.setAttribute(bits[0].trim(), window.t(bits[1].trim()));
      });
    });
  };

  /** يبدّل اللغة ويعيد رسم كل المحتوى الديناميكي */
  window.setLang = function (lang, skipStore) {
    var next = lang === 'en' ? 'en' : 'ar';
    var html = document.documentElement;
    html.setAttribute('lang', next);
    html.setAttribute('dir', next === 'en' ? 'ltr' : 'rtl');

    if (!skipStore) {
      try { localStorage.setItem(STORAGE_KEY, next); } catch (e) { /* private mode */ }
    }

    window.applyI18n();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: next } }));
  };

  /* اللغة الافتراضية: المحفوظة، وإلا العربية */
  window.initialLang = saved() === 'en' ? 'en' : 'ar';
})();
